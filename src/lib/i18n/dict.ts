export type Lang = "en" | "ur";

export function translate(key: string, lang: Lang, vars?: Record<string, string | number>): string {
  const entry = DICT[key];
  let text = entry ? entry[lang === "ur" ? 1 : 0] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  return text;
}

