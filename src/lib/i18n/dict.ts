export function translateError(message: string, lang: Lang): string {
  if (lang !== "ur") return message;
  for (const [re, ur] of ERROR_PATTERNS) if (re.test(message)) return message.replace(re, ur);
  return `${DICT["c.errorPrefix"][1]}: ${message}`;
}
